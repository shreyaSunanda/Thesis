"""
Attach the unhandled-input gap detector to a generated module.

WHY THIS EXISTS, and why plain deadlock checking was not enough:

A deadlock is "no action is enabled". Protocols are *supposed* to reach such
states - "SHALL close the session and report an error", "perform no further
processing", "remove the Exchange" all describe defined endpoints. Running
deadlock detection over 40 generated models produced 14 hits, and reading them
showed every single one was either a legitimate ending the spec explicitly
prescribes, or a section whose content lives in figures the text extractor
cannot see. Zero real findings, because deadlock cannot distinguish "the spec
says stop" from "the spec forgot to say".

The hand-written ArmFailSafe.tla gets this right with its UndefinedTransition
catch-all: it fires only when a MESSAGE ARRIVES that no (state, message) rule
handles. This module generalises that, as an invariant rather than an action,
so nothing has to be added to the model itself (the prompt forbids the model
from writing its own catch-all precisely so a gap cannot be faked):

    NoUnhandledInput ==
        (pendingInput # NoInput) => ENABLED (Next /\\ pendingInput' # pendingInput)

Read: if something is waiting to be handled, some action must be able to
consume it. It is vacuously true whenever nothing is pending, so a protocol
that simply ends never trips it. It trips exactly when an event arrived in a
state the spec text never considered - which is the thesis's B.4.3 question.

Verified against ground truth, with one caveat worth stating: ArmFailSafe.tla
itself names its variables pendingMsg/NullValue/Messages, so this detector
reports `no_shape` on it and cannot check it as written. On a copy renamed to
the mandated shape it reproduces the known finding (CommissioningComplete
received while Disarmed) without using that module's own UndefinedTransition
logic to do so. See tests/test_gap_detector.py, which pins both facts - the
claim lived only in this comment until it was tested, and the first half of it
turned out to be false.
"""
import re

INPUT_VAR = "pendingInput"
NO_INPUT_CONST = "NoInput"
INPUTS_CONST = "Inputs"
INVARIANT_NAME = "NoUnhandledInput"
OPERATIONAL_DEF = "Operational"
OPERATIONAL_INVARIANT = "NoUnhandledInputOperational"


def has_input_shape(plan: dict) -> bool:
    """True if the module declares the input shape rule 4a mandates."""
    return (INPUT_VAR in plan.get("variables", [])
            and NO_INPUT_CONST in plan.get("constants", []))


ALPHABET_DEF = "InputAlphabet"


def build_detector_module(module_name: str, alphabet_tla: str = "",
                          has_operational: bool = False) -> str:
    """
    The wrapper module carrying the invariant. Generated, never model-written.

    `alphabet_tla` is the set of inputs the module can actually recognise,
    recovered from its own guards. It is defined HERE and bound to the Inputs
    constant by the cfg, because a cfg can only assign model values or literals
    - it cannot express a set of strings taken from the module's own text.
    Without it Inputs holds model values no guard matches, and every module
    reports a spurious gap on its first input.
    """
    alphabet_block = (f"\n{ALPHABET_DEF} == {alphabet_tla}\n"
                      if alphabet_tla else "")
    # The same question restricted to states the module says it is really in
    # (rule 4b). Checked as a SEPARATE invariant in its own config, because
    # TLC stops at the first violation and the weak one would otherwise mask
    # it. A violation here ranks above one of the plain invariant: the event
    # arrived somewhere the device genuinely sits, not in setup scaffolding.
    operational_block = (
        f"\n{OPERATIONAL_INVARIANT} ==\n"
        f"    ({OPERATIONAL_DEF} /\\ {INPUT_VAR} # {NO_INPUT_CONST})\n"
        f"        => ENABLED (Next /\\ {INPUT_VAR}' # {INPUT_VAR})\n"
        if has_operational else "")
    return f"""---- MODULE {module_name}_MC ----
\\* GENERATED BY THE GAP-DETECTION HARNESS - do not edit by hand.
\\*
\\* Fires when an input is pending that no action of Next can consume: an event
\\* arrived in a state the spec text defines no handling for. Stays silent when
\\* the protocol simply ends, because the implication is vacuous once nothing is
\\* pending - which is what plain deadlock checking got wrong.
EXTENDS {module_name}
{alphabet_block}
{INVARIANT_NAME} ==
    ({INPUT_VAR} # {NO_INPUT_CONST})
        => ENABLED (Next /\\ {INPUT_VAR}' # {INPUT_VAR})
{operational_block}====
"""


def build_detector_config(plan: dict, constant_lines: list,
                          bind_alphabet: bool = False,
                          invariant: str = None) -> str:
    """
    Config for the wrapper. Deadlock checking is switched OFF deliberately:
    the whole point is that a stopped protocol is not a finding, and leaving it
    on would re-report every legitimate endpoint as noise.

    With `bind_alphabet`, the Inputs constant is bound to the InputAlphabet
    operator defined in the wrapper (`Inputs <- InputAlphabet`) instead of
    being assigned model values. A cfg cannot write a set of strings for a
    constant, so the override is the only way to hand the module an input
    alphabet its own guards recognise.
    """
    lines = []
    if plan.get("uses_spec"):
        lines.append("SPECIFICATION Spec")
    else:
        lines.append("INIT Init")
        lines.append("NEXT Next")
    lines.append(f"INVARIANT {invariant or INVARIANT_NAME}")
    for inv in plan.get("invariants", []):
        lines.append(f"INVARIANT {inv}")
    if bind_alphabet:
        # Drop the model-value assignment the generic classifier produced for
        # Inputs; the override below replaces it.
        constant_lines = [l for l in constant_lines
                          if l.split("=")[0].strip() != INPUTS_CONST]
        constant_lines = list(constant_lines) + [
            f"    {INPUTS_CONST} <- {ALPHABET_DEF}"]
    if constant_lines:
        lines.append("")
        lines.append("CONSTANTS")
        lines.extend(constant_lines)
    return "\n".join(lines) + "\n"


def missing_shape_reason(plan: dict) -> str:
    """Explains, for a report, exactly which part of rule 4a a module skipped."""
    missing = []
    if INPUT_VAR not in plan.get("variables", []):
        missing.append(f"VARIABLE {INPUT_VAR}")
    if NO_INPUT_CONST not in plan.get("constants", []):
        missing.append(f"CONSTANT {NO_INPUT_CONST}")
    if INPUTS_CONST not in plan.get("constants", []):
        missing.append(f"CONSTANT {INPUTS_CONST}")
    return ("module does not declare the mandatory input shape (missing "
            + ", ".join(missing) + ") - no gap detection is possible on it")


def extract_pending_value(trace: str) -> str:
    """The input that was left unhandled, pulled from a counterexample trace."""
    hits = re.findall(rf"{INPUT_VAR}\s*=\s*(.+)", trace)
    return hits[-1].strip() if hits else ""
